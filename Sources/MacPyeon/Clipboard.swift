import AppKit
import MacPyeonCore
import SwiftUI

struct ClipItem: Identifiable, Codable, Equatable {
    var id = UUID()
    var text: String?
    /// 이미지는 메모리에만 둔다(디스크에 저장하지 않음).
    var image: Data?
    var date = Date()
    var pinned = false

    enum CodingKeys: String, CodingKey { case id, text, date, pinned }

    var preview: String {
        if let text {
            let oneLine = text.replacingOccurrences(of: "\n", with: " ").trimmingCharacters(in: .whitespaces)
            return oneLine.count > 80 ? String(oneLine.prefix(80)) + "…" : oneLine
        }
        return "🖼 이미지"
    }
}

/// 클립보드 기록. 0.5초마다 변경을 확인한다.
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    static let limit = 100

    @Published private(set) var items: [ClipItem] = []
    var recordHistory = false
    var cleanURLs = false

    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private var ignoreChange: Int?

    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    private var storeURL: URL {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("MacPyeon", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir.appendingPathComponent("clipboard.json")
    }

    private init() {
        if let data = try? Data(contentsOf: storeURL), let saved = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = saved
        }
    }

    func update(record: Bool, clean: Bool) {
        // 기록을 끄면 저장된 기록도 지운다(개인정보).
        if recordHistory && !record { clear(keepPinned: false) }
        recordHistory = record
        cleanURLs = clean
        let wanted = record || clean
        if wanted && timer == nil {
            lastChange = NSPasteboard.general.changeCount
            let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
            RunLoop.main.add(t, forMode: .common)
            timer = t
        } else if !wanted {
            timer?.invalidate()
            timer = nil
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if ignoreChange == pb.changeCount { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipTypes) else { return }

        if var text = pb.string(forType: .string), !text.isEmpty {
            if cleanURLs, let cleaned = URLCleaner.clean(text) {
                pb.clearContents()
                pb.setString(cleaned, forType: .string)
                lastChange = pb.changeCount
                text = cleaned
            }
            if recordHistory { add(ClipItem(text: text)) }
        } else if recordHistory, !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
                  let raw = pb.data(forType: .png) ?? pb.data(forType: .tiff), raw.count < 30_000_000 {
            // 이미지 변환은 무거워서 메인 스레드(키보드 처리)를 막지 않게 백그라운드에서 한다.
            DispatchQueue.global(qos: .utility).async { [weak self] in
                guard let png = NSImage(data: raw)?.pngData, png.count < 8_000_000 else { return }
                DispatchQueue.main.async { self?.add(ClipItem(image: png)) }
            }
        }
    }

    private func add(_ item: ClipItem) {
        if let text = item.text, let existing = items.firstIndex(where: { $0.text == text }) {
            var moved = items.remove(at: existing)
            moved.date = Date()
            items.insert(moved, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        let unpinned = items.enumerated().filter { !$0.element.pinned }.map(\.offset)
        if unpinned.count > Self.limit {
            for index in unpinned.suffix(unpinned.count - Self.limit).reversed() { items.remove(at: index) }
        }
        // 이미지는 메모리를 많이 써서 최근 20개만 둔다.
        let images = items.enumerated().filter { $0.element.image != nil && !$0.element.pinned }.map(\.offset)
        if images.count > 20 {
            for index in images.suffix(images.count - 20).reversed() { items.remove(at: index) }
        }
        save()
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(of: item) else { return }
        items[i].pinned.toggle()
        save()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    func clear(keepPinned: Bool = true) {
        items.removeAll { !keepPinned || !$0.pinned }
        save()
    }

    private func save() {
        let textOnly = items.filter { $0.text != nil }
        if let data = try? JSONEncoder().encode(textOnly) { try? data.write(to: storeURL, options: .atomic) }
    }

    /// 항목을 클립보드에 올리고 지금 앱에 붙여넣는다.
    func paste(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let text = item.text { pb.setString(text, forType: .string) }
        if let image = item.image { pb.setData(image, forType: .png) }
        lastChange = pb.changeCount
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) {
            KeySender.post(key: KeyCode.v, modifiers: [.command])
        }
    }

    /// 서식을 뺀 글자만 붙여넣고, 클립보드 원래 내용은 되돌린다.
    func pastePlainText() {
        let pb = NSPasteboard.general
        guard let text = pb.string(forType: .string) else { return }
        let saved: [NSPasteboardItem] = (pb.pasteboardItems ?? []).map { original in
            let copy = NSPasteboardItem()
            for type in original.types { if let data = original.data(forType: type) { copy.setData(data, forType: type) } }
            return copy
        }
        pb.clearContents()
        pb.setString(text, forType: .string)
        ignoreChange = pb.changeCount
        KeySender.post(key: KeyCode.v, modifiers: [.command])
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.4) {
            pb.clearContents()
            pb.writeObjects(saved)
            self.ignoreChange = pb.changeCount
            self.lastChange = pb.changeCount
        }
    }
}

extension NSImage {
    var pngData: Data? {
        guard let tiff = tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}

// MARK: - ⌃⌥V 목록 창

private final class KeyPanel: NSPanel {
    override var canBecomeKey: Bool { true }
}

final class ClipboardPanel {
    static let shared = ClipboardPanel()
    private var panel: NSPanel?
    private var monitor: Any?
    private let model = ClipboardPanelModel()

    func toggle() {
        if panel?.isVisible == true { close() } else { show() }
    }

    func show() {
        model.query = ""
        model.selection = 0
        let panel = self.panel ?? makePanel()
        self.panel = panel
        let mouse = NSEvent.mouseLocation
        let screen = NSScreen.screens.first { $0.frame.contains(mouse) } ?? NSScreen.main
        let size = panel.frame.size
        var origin = CGPoint(x: mouse.x - size.width / 2, y: mouse.y - size.height - 10)
        if let v = screen?.visibleFrame {
            origin.x = min(max(origin.x, v.minX + 8), v.maxX - size.width - 8)
            origin.y = min(max(origin.y, v.minY + 8), v.maxY - size.height - 8)
        }
        panel.setFrameOrigin(origin)
        panel.makeKeyAndOrderFront(nil)
        monitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] event in
            guard let self else { return event }
            switch event.keyCode {
            case 125: self.model.move(1); return nil          // ↓
            case 126: self.model.move(-1); return nil         // ↑
            case 53: self.close(); return nil                 // Esc
            case 36, 76: self.pick(self.model.selected); return nil
            default: return event
            }
        }
    }

    func close() {
        panel?.orderOut(nil)
        if let monitor { NSEvent.removeMonitor(monitor) }
        monitor = nil
    }

    private func pick(_ item: ClipItem?) {
        close()
        guard let item else { return }
        ClipboardHistory.shared.paste(item)
    }

    private func makePanel() -> NSPanel {
        // nonactivatingPanel: 지금 쓰던 앱이 계속 활성 상태로 남아 있어서 붙여넣기가 그 앱으로 간다.
        let p = KeyPanel(contentRect: NSRect(x: 0, y: 0, width: 420, height: 460),
                         styleMask: [.nonactivatingPanel, .titled, .fullSizeContentView, .closable],
                         backing: .buffered, defer: false)
        p.titleVisibility = .hidden
        p.titlebarAppearsTransparent = true
        p.isFloatingPanel = true
        p.level = .popUpMenu
        p.hidesOnDeactivate = false
        p.isMovableByWindowBackground = true
        p.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
        p.contentView = NSHostingView(rootView: ClipboardPanelView(model: model, history: .shared) { [weak self] in
            self?.pick($0)
        })
        NotificationCenter.default.addObserver(forName: NSWindow.didResignKeyNotification, object: p, queue: .main) { [weak self] _ in
            self?.close()
        }
        return p
    }
}

final class ClipboardPanelModel: ObservableObject {
    @Published var query = ""
    @Published var selection = 0
    var visible: [ClipItem] = []

    var selected: ClipItem? { visible.indices.contains(selection) ? visible[selection] : nil }

    func move(_ delta: Int) {
        guard !visible.isEmpty else { return }
        selection = min(max(selection + delta, 0), visible.count - 1)
    }
}

private struct ClipboardPanelView: View {
    @ObservedObject var model: ClipboardPanelModel
    @ObservedObject var history: ClipboardHistory
    let onPick: (ClipItem) -> Void

    private var filtered: [ClipItem] {
        let pinned = history.items.filter(\.pinned), rest = history.items.filter { !$0.pinned }
        let all = pinned + rest
        guard !model.query.isEmpty else { return all }
        return all.filter { $0.text?.localizedCaseInsensitiveContains(model.query) ?? false }
    }

    var body: some View {
        let items = filtered
        let _ = { model.visible = items }()
        VStack(spacing: 0) {
            HStack {
                Image(systemName: "magnifyingglass").foregroundStyle(.secondary)
                TextField("클립보드 기록 검색", text: $model.query)
                    .textFieldStyle(.plain)
                    .font(.title3)
                    .onChange(of: model.query) { _ in model.selection = 0 }
            }
            .padding(12)
            Divider()
            if items.isEmpty {
                Spacer()
                Text(history.items.isEmpty ? "아직 복사한 내용이 없어요" : "찾는 내용이 없어요").foregroundStyle(.secondary)
                Spacer()
            } else {
                ScrollViewReader { proxy in
                    List(Array(items.enumerated()), id: \.element.id) { index, item in
                        row(item, selected: index == model.selection)
                            .id(item.id)
                            .contentShape(Rectangle())
                            .onTapGesture { onPick(item) }
                            .contextMenu {
                                Button(item.pinned ? "고정 해제" : "고정") { history.togglePin(item) }
                                Button("삭제", role: .destructive) { history.remove(item) }
                            }
                    }
                    .listStyle(.plain)
                    .onChange(of: model.selection) { i in
                        if items.indices.contains(i) { proxy.scrollTo(items[i].id) }
                    }
                }
            }
            Divider()
            Text("↑↓ 선택 · ↩ 붙여넣기 · Esc 닫기 · 오른쪽 클릭으로 고정")
                .font(.caption)
                .foregroundStyle(.secondary)
                .padding(8)
        }
        .frame(width: 420, height: 460)
    }

    @ViewBuilder
    private func row(_ item: ClipItem, selected: Bool) -> some View {
        HStack(spacing: 8) {
            if let data = item.image, let image = NSImage(data: data) {
                Image(nsImage: image).resizable().scaledToFit().frame(height: 44)
            } else {
                Text(item.preview).lineLimit(2)
            }
            Spacer()
            if item.pinned { Image(systemName: "pin.fill").foregroundStyle(.orange).font(.caption) }
        }
        .padding(.vertical, 4)
        .padding(.horizontal, 6)
        .background(selected ? Color.accentColor.opacity(0.2) : .clear, in: RoundedRectangle(cornerRadius: 6))
    }
}
